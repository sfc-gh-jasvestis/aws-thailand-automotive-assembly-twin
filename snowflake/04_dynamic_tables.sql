  TARGET_LAG = '30 days' WAREHOUSE = TOURISM_WH
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH thresh AS (
  SELECT PERCENTILE_CONT(0.09) WITHIN GROUP (ORDER BY KPI_ASSEMBLY_LINE_OEE) AS T
  FROM RAW.EQUIPMENT_TELEMETRY
)
SELECT
  e.ID AS ENTITY_ID,
  e.NAME AS ENTITY_NAME,
  e.REGION,
  e.CATEGORY,
  e.STATUS,
  COUNT(*) AS EVENT_COUNT,
  SUM(CASE WHEN f.KPI_ASSEMBLY_LINE_OEE <= (SELECT T FROM thresh) THEN 1 ELSE 0 END) AS ALERT_COUNT,
  ROUND(AVG(f.KPI_ASSEMBLY_LINE_OEE), 2) AS AVG_ASSEMBLY_LINE_OEE,
  ROUND(AVG(f.KPI_DIGITAL_TWIN_SYNC), 2) AS AVG_DIGITAL_TWIN_SYNC,
