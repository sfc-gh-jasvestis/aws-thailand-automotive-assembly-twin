  ROUND(AVG(f.KPI_CYCLE_TIME_VARIANCE), 2) AS AVG_CYCLE_TIME_VARIANCE,
  ROUND(AVG(f.KPI_ENERGY_PER_UNIT), 2) AS AVG_ENERGY_PER_UNIT,
  ROUND(AVG(f.KPI_SIMULATION_ACCURACY), 2) AS AVG_SIMULATION_ACCURACY
FROM RAW.EQUIPMENT_TELEMETRY f
JOIN RAW.ASSEMBLY_LINES e ON e.ID = f.ENTITY_ID
